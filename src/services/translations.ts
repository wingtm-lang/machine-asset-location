export type Lang = 'id' | 'en';

export function getTranslation(key: string, lang: Lang = 'id'): string {
  const item = defaultTranslations[key];
  if (!item) return key;
  return lang === 'en' ? item.en : item.id;
}

/**
 * Terjemahan dengan parameter. Contoh:
 *   formatTranslation('xfer_showing', lang, { from: 1, to: 10, total: 42 })
 *   -> "Menampilkan 1-10 dari 42 transfer" / "Showing 1-10 of 42 transfers"
 * Placeholder yang tidak diberi nilai dibiarkan apa adanya.
 */
export function formatTranslation(
  key: string,
  lang: 'id' | 'en' = 'id',
  params: Record<string, string | number> = {}
): string {
  return getTranslation(key, lang).replace(/\{(\w+)\}/g, (m, name) =>
    name in params ? String(params[name]) : m
  );
}

/** Locale untuk tanggal/angka mengikuti bahasa yang dipilih. */
export const localeOf = (lang: Lang): string => (lang === 'en' ? 'en-GB' : 'id-ID');

export type TFn = (key: string, params?: Record<string, string | number>) => string;

/**
 * Pembuat fungsi terjemah untuk satu bahasa:  const t = makeT(language);  t('kunci', { n: 3 })
 * Bila params.n === 1 dan ada kunci "<kunci>_one", kunci itu yang dipakai (bentuk tunggal bahasa Inggris).
 */
export function makeT(lang: Lang): TFn {
  return (key, params) => {
    const n = params && typeof params.n === 'number' ? params.n : undefined;
    const k = n === 1 && defaultTranslations[`${key}_one`] ? `${key}_one` : key;
    return formatTranslation(k, lang, params);
  };
}

